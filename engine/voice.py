"""Narrator recordings: which texts are spoken and how a recording is named.

Every scene line, option and ending title is recorded separately (lines
shown only for some flags must be playable on their own). A recording is
named by a hash of the voice settings and the text, so an unchanged text
keeps its recording and a changed text or voice gets a new one.

Generated by tools/nagraj.py (in the Docker build); no Piper needed here.
"""

from __future__ import annotations

import hashlib
import wave
from pathlib import Path

from .scenario import Scenario

# Chosen 2026-11-01 (docs/zalozenia.md -> "Głos")
VOICE = "pl_PL-mc_speech-medium"
LENGTH_SCALE = 1.2  # 20% slower than the model's default
SENTENCE_SILENCE = 0.6  # seconds between sentences inside one recording


def key(text: str) -> str:
    """File name (without .wav) of the recording of this text."""
    settings = f"{VOICE}|{LENGTH_SCALE}|{SENTENCE_SILENCE}|{text}"
    return hashlib.sha1(settings.encode("utf-8")).hexdigest()[:16]


def texts(scenario: Scenario) -> list[str]:
    """Everything the narrator reads, without repeats, in file order."""
    found: dict[str, None] = {}
    for scene in scenario.scenes.values():
        for paragraph in scene.paragraphs:
            for line in paragraph:
                found[line.text] = None
        for option in scene.options:
            found[option.text] = None
        if scene.ending:
            found[scene.ending] = None
    return [text for text in found if text.strip()]


def duration(path: Path) -> float:
    with wave.open(str(path), "rb") as wav:
        return wav.getnframes() / wav.getframerate()


class Recordings:
    """Recordings in a directory -> {"url", "duration"} for a text, or None."""

    def __init__(self, directory: Path, url_prefix: str):
        self.url_prefix = url_prefix.rstrip("/")
        self.durations = {}
        if directory.is_dir():
            self.durations = {p.stem: round(duration(p), 2) for p in directory.glob("*.wav")}

    def __call__(self, text: str) -> dict | None:
        name = key(text)
        if name not in self.durations:
            return None
        return {"url": f"{self.url_prefix}/{name}.wav", "duration": self.durations[name]}
